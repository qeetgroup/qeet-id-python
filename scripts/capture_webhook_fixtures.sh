#!/usr/bin/env bash
# Capture webhook deliveries signed by qeet-id-server's own code.
#
#   scripts/capture_webhook_fixtures.sh /path/to/qeet-id-server [git-ref] > tests/fixtures/webhook_deliveries.json
#
# Copies the server's Event type and its deliver and sign functions
# (internal/developer/webhooks) verbatim out of the given ref, without checking
# it out, wraps them in a small Go program, and lets them post real deliveries
# to a local receiver. The receiver records each delivery's exact body and
# headers. Needs Go.
set -euo pipefail

server=${1:?usage: $0 /path/to/qeet-id-server [git-ref]}
ref=${2:-origin/main}
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

webhook=$(git -C "$server" show "$ref:internal/developer/webhooks/webhook.go")
events=$(git -C "$server" show "$ref:internal/developer/webhooks/events.go")
# A top-level declaration runs from its first line to the first line that is just "}".
extract() { awk -v start="$1" 'index($0, start) == 1 { on = 1 } on { print } on && $0 == "}" { exit }'; }

{
  cat <<'GO'
// Generated by scripts/capture_webhook_fixtures.sh: the server's deliver, sign
// and Event, copied verbatim, posting to a local recorder.
package main

import (
	"bytes"
	"context"
	"crypto/hmac"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"io"
	"net/http"
	"net/http/httptest"
	"os"
	"strconv"
	"strings"
	"time"
)

// The server's IDs are uuid.UUID, which encodes to JSON as the same string.
type uuidString = string

type Service struct{ client *http.Client }

GO
  printf '%s\n' "$events" | extract "type Event struct" | sed 's/uuid\.UUID/uuidString/g'
  echo
  printf '%s\n' "$webhook" | extract "func (s *Service) deliver(" | sed 's/deliveryID uuid\.UUID/deliveryID uuidString/; s/deliveryID\.String()/deliveryID/'
  echo
  printf '%s\n' "$webhook" | extract "func sign("
  cat <<'GO'

type delivery struct {
	Name       string            `json:"name"`
	SignedWith []string          `json:"signed_with"`
	Headers    map[string]string `json:"headers"`
	Body       string            `json:"body"`
}

func main() {
	var got delivery
	recorder := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		body, _ := io.ReadAll(r.Body)
		got.Body = string(body)
		got.Headers = map[string]string{}
		for _, name := range []string{"Content-Type", "X-Qeet-Event", "X-Qeet-Delivery-Id", "X-Qeet-Timestamp", "X-Qeet-Signature"} {
			got.Headers[name] = r.Header.Get(name)
		}
		w.WriteHeader(http.StatusNoContent)
	}))
	defer recorder.Close()
	s := &Service{client: recorder.Client()}

	tenant := "7d2f9a1c-3b4e-4c5d-8e6f-1a2b3c4d5e6f"
	occurred := time.Date(2026, 11, 5, 9, 30, 0, 0, time.UTC)
	cases := []struct {
		name, eventID, eventType string
		data                     map[string]any
		secrets                  []string
	}{
		{"user.created", "5a6b7c8d-9e0f-4a1b-8c2d-3e4f5a6b7c8d", "user.created",
			map[string]any{"user_id": "c1d2e3f4-a5b6-4c7d-8e9f-0a1b2c3d4e5f", "tenant_id": tenant, "email": "meera@brightleaffoods.in", "source": "admin"},
			[]string{"fixture-signing-value-a"}},
		{"test.ping during a secret rotation", "9c8b7a6d-5e4f-4a3b-8c2d-1e0f9a8b7c6d", "test.ping",
			map[string]any{"subscription_id": "e1f2a3b4-c5d6-4e7f-8a9b-0c1d2e3f4a5b"},
			[]string{"fixture-signing-value-new", "fixture-signing-value-old"}},
		{"user.updated with non-ASCII and HTML-escaped text", "3e4f5a6b-7c8d-4e9f-8a0b-1c2d3e4f5a6b", "user.updated",
			map[string]any{"user_id": "c1d2e3f4-a5b6-4c7d-8e9f-0a1b2c3d4e5f", "tenant_id": tenant, "display_name": "Zoë Ramírez <ops & finance>", "status": "active"},
			[]string{"fixture-signing-value-a"}},
	}
	var out []delivery
	for _, c := range cases {
		data, _ := json.Marshal(c.data)
		body, _ := json.Marshal(Event{ID: c.eventID, Type: c.eventType, TenantID: tenant, OccurredAt: occurred, Data: data})
		got = delivery{Name: c.name, SignedWith: c.secrets}
		if _, _, err := s.deliver(context.Background(), "0b6f5c2e-6f1a-4b8e-9c3d-2a7e5f1c9d40", recorder.URL, c.secrets, c.eventType, body); err != nil {
			panic(err)
		}
		out = append(out, got)
	}
	enc := json.NewEncoder(os.Stdout)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	_ = enc.Encode(map[string]any{
		"description": "Webhook deliveries made by qeet-id-server's own deliver and sign (internal/developer/webhooks), " +
			"copied from " + os.Getenv("CAPTURE_REF") + " by scripts/capture_webhook_fixtures.sh and posted to a local receiver. " +
			"Each body is the exact bytes received; each signature is the server's. Don't edit by hand: a changed byte must fail verification.",
		"deliveries": out,
	})
	_ = bytes.MinRead
	_ = errors.New
	_ = strconv.Itoa
	_ = strings.Join
	_ = hex.EncodeToString
	_ = hmac.New
	_ = sha256.New
}
GO
} > "$work/main.go"

(cd "$work" && go mod init capture >/dev/null 2>&1 && CAPTURE_REF="$ref ($(git -C "$server" rev-parse --short "$ref"))" go run .)
